# Question 9:
# Print the type of five different variables: an int, a float, a string,
# a boolean, and a list — using type().

int_var = 42
float_var = 3.14
string_var = "Hello"
bool_var = True
list_var = [1, 2, 3]

print(type(int_var))     # <class 'int'>
print(type(float_var))   # <class 'float'>
print(type(string_var))  # <class 'str'>
print(type(bool_var))    # <class 'bool'>
print(type(list_var))    # <class 'list'>

# Time Complexity: O(1) 
# Space Complexity: O(1)
